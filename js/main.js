// ===== 沉浸模式（增强版：地图联动） =====



let immersiveActive = false;



let immersiveIndex = 0;



let immersiveMarker = null;



let immersiveAutoplayTimer = null;



const immersiveStops = ['hangzhou', 'xtianmu', 'jiande', 'yushan', 'jian', 'taihe', 'yishan', 'zunyi', 'meitan'];



function toggleImmersive() {

  immersiveActive = !immersiveActive;

  const overlay = document.getElementById('immersive-overlay');

  if (immersiveActive) {

    immersiveIndex = 0;

    overlay.classList.add('active');

    document.body.style.overflow = 'hidden';

    // Scroll to map first so it's visible behind the story card

    var mapSection = document.getElementById('map-section');

    if (mapSection) mapSection.scrollIntoView({ behavior: 'smooth' });

    setTimeout(function() {

      if (map) {

        map.invalidateSize();

        renderImmersive();

      }

    }, 600);

  } else {

    overlay.classList.remove('active');

    document.body.style.overflow = '';

    stopAutoplay();

    if (immersiveMarker && map) {

      map.removeLayer(immersiveMarker);

      immersiveMarker = null;

    }

    if (window._immersiveTrail && map) {

      map.removeLayer(window._immersiveTrail);

      window._immersiveTrail = null;

    }

  }

}



function renderImmersive() {

  const id = immersiveStops[immersiveIndex];

  const data = locationData[id];

  document.getElementById('immersive-counter').textContent = '第 ' + (immersiveIndex + 1) + ' 站 / 共 ' + immersiveStops.length + ' 站';

  document.getElementById('immersive-title').textContent = data.name + ' · ' + data.period;

  document.getElementById('immersive-text').textContent = data.story;

  // Update progress bar

  var progress = document.getElementById('immersive-progress-fill');

  if (progress) {

    var pct = ((immersiveIndex + 1) / immersiveStops.length) * 100;

    progress.style.width = pct + '%';

  }

  // Fly map and add pulsing marker

  if (map && data.lat && data.lng) {

    const gcj = wgs84ToGcj02(data.lat, data.lng);

    map.flyTo(gcj, 7, { duration: 1.8, easeLinearity: 0.25 });

    if (immersiveMarker) map.removeLayer(immersiveMarker);

    var pulseIcon = L.divIcon({

      className: 'immersive-pulse-marker',

      html: '<div class="pulse-core" style="background:' + data.color + ';"></div><div class="pulse-ring" style="border-color:' + data.color + ';"></div>',

      iconSize: [30, 30],

      iconAnchor: [15, 15]

    });

    immersiveMarker = L.marker(gcj, { icon: pulseIcon, interactive: false, zIndexOffset: 1000 }).addTo(map);

    updateImmersiveTrail();

  }

  // Update stop dots

  document.querySelectorAll('.immersive-stop-dot').forEach(function(dot, idx) {

    dot.classList.toggle('visited', idx < immersiveIndex);

    dot.classList.toggle('current', idx === immersiveIndex);

  });

}



function updateImmersiveTrail() {

  if (window._immersiveTrail && map) map.removeLayer(window._immersiveTrail);

  var coords = [];

  for (var i = 0; i <= immersiveIndex; i++) {

    var sid = immersiveStops[i];

    var d = locationData[sid];

    if (d && d.lat && d.lng) coords.push(wgs84ToGcj02(d.lat, d.lng));

  }

  if (coords.length >= 2) {

    window._immersiveTrail = L.polyline(coords, {

      color: '#C41E3A',

      weight: 4,

      opacity: 0.85,

      dashArray: '8, 6',

      lineCap: 'round'

    }).addTo(map);

  }

}



function immersivePrev() {

  immersiveIndex = (immersiveIndex - 1 + immersiveStops.length) % immersiveStops.length;

  renderImmersive();

}



function immersiveNext() {

  immersiveIndex = (immersiveIndex + 1) % immersiveStops.length;

  renderImmersive();

}



function toggleAutoplay() {

  if (immersiveAutoplayTimer) {

    stopAutoplay();

  } else {

    startAutoplay();

  }

}



function startAutoplay() {

  immersiveAutoplayTimer = setInterval(function() {

    immersiveNext();

  }, 8000);

  var btn = document.getElementById('immersive-autoplay');

  if (btn) btn.textContent = '⏸ 暂停';

}



function stopAutoplay() {

  if (immersiveAutoplayTimer) {

    clearInterval(immersiveAutoplayTimer);

    immersiveAutoplayTimer = null;

  }

  var btn = document.getElementById('immersive-autoplay');

  if (btn) btn.textContent = '▶ 自动播放';

}



function jumpToImmersive(idx) {



  immersiveIndex = idx;



  renderImmersive();



}


